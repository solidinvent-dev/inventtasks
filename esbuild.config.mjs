/**
 * esbuild.config.mjs — bundles src/main.ts into the single main.js Obsidian
 * loads.
 *
 *   node esbuild.config.mjs             # dev: watch mode + inline sourcemaps
 *   node esbuild.config.mjs production  # release: minified, no sourcemaps
 *
 * Run through npm: `npm run dev` / `npm run build` (build also type-checks
 * with tsc first). The version number is NOT touched here — releases bump it
 * via scripts/bump-version.mjs (see `npm run full-deploy`).
 *
 * `external` lists everything Obsidian provides at runtime (obsidian API,
 * electron, CodeMirror packages, Node builtins) so they stay out of the
 * bundle. The size guard lives in scripts/check-bundle-size.mjs.
 */
import esbuild from "esbuild";
import process from "process";
import { builtinModules } from "node:module";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
*/`;

const prod = process.argv[2] === "production";

const context = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtinModules,
  ],
  format: "cjs",
  target: "es2018",
  // The browser web app is always licensed (its server gates access); in the
  // plugin that branch compiles away and data/license.ts checks the key.
  define: { "globalThis.__IT_WEB__": "false" },
  loader: {
    ".png": "dataurl",
    ".svg": "dataurl",
    ".webp": "dataurl",
  },
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  minify: prod,
  outfile: "main.js",
});

if (prod) {
  await context.rebuild();
  process.exit(0);
} else {
  await context.watch();
}
